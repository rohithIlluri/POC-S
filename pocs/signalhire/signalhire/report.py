def _bar(value: int, color: str) -> str:
    return (f'<span class="bar"><i style="width:{value}%;background:{color}"></i></span>')


def _reason_html(signal_dict: dict) -> str:
    code = signal_dict["code"]
    evidence = json.dumps(signal_dict["evidence"], indent=2, default=str)
    return (
        '<div class="reason">'
        f'<span class="code">{html.escape(code)}</span>'
        f'<span class="sev">{html.escape(signal_dict["severity"])}</span>'
        f'<span class="sev">impact {signal_dict["score_impact"]:+.2f}</span>'
        f'<div class="why">{html.escape(CODE_TEXT.get(code, "—"))}</div>'
        f"<pre>{html.escape(evidence)}</pre>"
        "</div>"
    )


def _app_html(app: ScoredApplication) -> str:
    d = app.as_dict()
    name = d["candidate"] or "(no name found)"
    reasons = "".join(_reason_html(r) for r in d["reason_codes"]) or \
        '<div class="empty">No signals fired — nothing to explain.</div>'

    # How the evidence combined: corroboration across independent analyzer
    # families is the thing that distinguishes a real finding from one noisy
    # detector, so the report says it plainly.
    ev = d.get("evidence") or {}
    families = ev.get("independent_families")
    combination = ""
    if families:
        discounted = sum(1 for c in ev.get("contributions", [])
                         if 0 < c.get("correlation_discount", 1) < 1)
        combination = (
            '<div class="combine">'
            f'{families} independent analyzer '
            f'{"family" if families == 1 else "families"} produced evidence'
            + (f'; {discounted} corroborating signal'
               f'{"" if discounted == 1 else "s"} discounted as correlated'
               if discounted else "")
            + "</div>"
        )

    return (
        '<details class="app">'
        "<summary>"
        f'<span class="chip {app.label}">{html.escape(LABEL_TEXT[app.label])}</span>'
        f'<span class="name">{html.escape(name)}</span>'
        '<span class="scores">'
        f'<span>effort {app.effort_score}{_bar(app.effort_score, "var(--genuine)")}</span>'
        f'<span>risk {app.risk_score}{_bar(app.risk_score, "var(--risk)")}</span>'
        f'<span>{len(d["reason_codes"])} signals</span>'
        "</span></summary>"
        '<div class="body">'
        f'<div class="path">{html.escape(d["source_path"])}</div>'
        f"{combination}{reasons}</div></details>"
    )


def render_html(result: ScanResult, title: str = "Application triage report") -> str:
    stats = result.stats
    labels = stats["labels"]
    tiles = "".join(
        f'<div class="tile"><div class="n {key}">{labels[key]}</div>'
        f'<div class="l">{html.escape(LABEL_TEXT[key])}</div></div>'
        for key in ("high_risk", "mass_generated", "needs_review", "genuine")
    )
    apps = "".join(_app_html(a) for a in result.applications) or \
        '<div class="empty">No documents found.</div>'
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    # A cross-scan reason code is only auditable next to the population it was
    # measured against, so the report states it: how much history this scan
    # could see, and how much of it it recognised.
    memory = stats.get("memory") or {}
    memory_note = ""
    if memory.get("enabled"):
        held = memory.get("documents_remembered", 0)
        memory_note = (
            f" Cross-scan signals were measured against {held} document"
            f"{'' if held == 1 else 's'} remembered from earlier scans; "
            f"{memory.get('documents_recognised', 0)} of the documents in "
            "this batch matched something already seen."
            if held else
            " No earlier scans were remembered for this account, so no "
            "cross-scan signal could fire.")

    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{html.escape(title)}</title><style>{_CSS}</style></head>
<body><div class="wrap">
<h1>{html.escape(title)}</h1>
<div class="sub">{stats['documents']} documents ·
 source <code>{html.escape(str(stats.get('source', 'in-memory')))}</code> ·
 sensitivity {html.escape(stats['sensitivity'])} ·
 signature DB {html.escape(stats['signature_db_version'])}
 ({stats['signatures_active']} active) ·
 JD {'provided' if stats['jd_provided'] else 'not provided'} ·
 generated {generated}</div>
<div class="assist"><strong>Assistive output.</strong> These labels are a triage
aid with the evidence attached, not a hiring decision. Nothing here should be
used as a sole or automatic basis for rejecting a candidate.</div>
<div class="tiles">{tiles}</div>
{apps}
<footer>Reason codes are reproducible against signature DB
{html.escape(stats['signature_db_version'])}. Rare-term idf source:
{html.escape(stats['idf_source'])}.{memory_note}</footer>
</div></body></html>"""


def render_json(result: ScanResult) -> str:
    return json.dumps(result.as_dict(), indent=2, default=str)


def render_text(result: ScanResult) -> str:
    stats = result.stats
    lines = [
        f"Scanned {stats['documents']} documents "
        f"(sensitivity: {stats['sensitivity']}, "
        f"signature DB: {stats['signature_db_version']})",
        "",
        "  {:<16}{}".format("high risk", stats["labels"]["high_risk"]),
        "  {:<16}{}".format("mass generated", stats["labels"]["mass_generated"]),
        "  {:<16}{}".format("needs review", stats["labels"]["needs_review"]),
        "  {:<16}{}".format("genuine", stats["labels"]["genuine"]),
        "",
    ]
    for app in result.applications:
        if app.label == "genuine":
            continue
        name = app.doc.identity.display_name or "(no name found)"
        codes = ", ".join(s.code for s in app.signals[:4]) or "—"
        lines.append(f"  [{app.label:<14}] effort {app.effort_score:>3} "
                     f"risk {app.risk_score:>3}  {name[:32]:<32} {codes}")
    if len(lines) == 8:
        lines.append("  Nothing flagged.")
    lines += ["", "Assistive output — review the evidence before acting on any label."]
    return "\n".join(lines)
